declare(strict_types=1);

namespace pocketmine\network\mcpe\protocol\mapping;

final class MappingTableBuilder{

	/**
	 * @param array<string, int> $networkData
	 * @param array<string, int> $coreData
	 * @param array<int, int>    &$networkToCoreData
	 * @param array<int, int>    &$coreToNetworkData
	 */
	public static function build(
		array $networkData,
		array $coreData,
		?array &$networkToCoreData,
		?array &$coreToNetworkData
	) : void{
		$networkToCoreData = [];
		$coreToNetworkData = [];

		foreach($networkData as $name => $networkId){
			if(!isset($coreData[$name])){
				continue;
			}

			$coreId = $coreData[$name];

			$networkToCoreData[$networkId] = $coreId;
			$coreToNetworkData[$coreId] = $networkId;
		}
	}
}
